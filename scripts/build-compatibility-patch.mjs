#!/usr/bin/env node
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import { createCompatibilityCompositionPatches } from '../lib/compatibility/composition.js'

// Generate from the compiled helper: function serialization must match shipped
// !!js guards exactly, rather than a TypeScript/transpiler-specific spelling.
const args = process.argv.slice(2)
assert(args.length === 0 || args.length === 1 && args[0] === '--check', 'Usage: node scripts/build-compatibility-patch.mjs [--check]')
const [stock, compatible] = createCompatibilityCompositionPatches()
const row = compatible.insert[0]
const output = '# Generated by scripts/build-compatibility-patch.mjs.\n' +
  '# Freeze one native provider per process; preserve active/pending services during HMR.\n' +
  '- id: ' + stock.id + '\n  name: ' + JSON.stringify(stock.name) + '\n  disabled: !!js ' + JSON.stringify(stock.disabled.__jsExpr) + '\n' +
  '- insert:\n    - id: ' + row.id + '\n      name: ' + JSON.stringify(row.name) + '\n      disabled: !!js ' + JSON.stringify(row.disabled.__jsExpr) + '\n' +
  '# Independent immutable Skills provider; stable remains the default.\n' +
  '- insert:\n    - id: dsh-mattpocock-skills\n      name: "@lmgatex/dsh-mattpocock-skills"\n      config:\n        channel: stable\n'
const url = new URL('../cordis.patch.yml', import.meta.url)
const existing = await readFile(url, 'utf8')
if (args[0] === '--check') assert(existing === output, 'Shipped compatibility patch differs from compiled expressions')
else if (existing !== output) await writeFile(url, output)
console.log(JSON.stringify({ check: args[0] === '--check', bytes: Buffer.byteLength(output) }))
